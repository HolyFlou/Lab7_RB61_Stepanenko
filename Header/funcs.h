#ifndef FUNCS_H
#define FUNCS_H

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>

/**
 * @brief Формує текстовий рядок, що містить таблицю результатів обчислень.
 *
 * @details Використовується для створення форматованого текстового представлення таблиці
 * значень на заданому проміжку. Виділяє пам'ять під рядок, який необхідно звільнити після використання.
 *
 * @param x1 Початкове значення інтервалу обчислень.
 * @param x2 Кінцеве значення інтервалу обчислень.
 * @param N Кількість розрахункових точок.
 * @param delta Крок зміни аргументу.
 *
 * @return Вказівник на рядок (char*), що містить сформовану таблицю.
 */
char* make_table(double x1, double x2, unsigned int N, double delta);

/**
 * @brief Записує таблицю в файл.
 *
 * @details Записує таблицю розрахованих значень разом з ідентифікаційною інформацією 
 * про користувача (група та ім'я).
 *
 * @param x1 Початкове значення інтервалу обчислень.
 * @param x2 Кінцеве значення інтервалу обчислень.
 * @param N Кількість розрахункових точок.
 * @param delta Крок зміни аргументу.
 * @param group Ідентифікатор групи.
 * @param name Ідентифікатор імені.
 */
void print_output_data(double x1, double x2, unsigned int N, double delta, char* group, char* name);

/**
 * @brief Записує масив розрахованих даних у бінарний файл.
 *
 * @details Обчислює значення для заданих параметрів проміжку та зберігає результати 
 * у бінарному форматі для подальшого зчитування.
 *
 * @param x1 Початкове значення інтервалу обчислень.
 * @param x2 Кінцеве значення інтервалу обчислень.
 * @param N Кількість розрахункових точок.
 * @param delta Крок зміни аргументу.
 */
void write_bin_file(double x1, double x2, unsigned int N, double delta);

/**
 * @brief Зчитує дані з бінарного файлу та виводить їх на екран.
 *
 * @details Використовується для перевірки коректності бінарного збереження даних. 
 * Читає збережену інформацію з файлу і формує вивід у зручному для читання форматі.
 *
 * @param x1 Початкове значення інтервалу обчислень.
 * @param x2 Кінцеве значення інтервалу обчислень.
 * @param N Кількість розрахункових точок.
 * @param delta Крок зміни аргументу.
 */
void print_bin_data(double x1, double x2, unsigned int N, double delta);

#endif // FUNCS_H